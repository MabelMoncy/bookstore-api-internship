"""Pydantic schemas and response DTOs for Books, Users, Notes, Authentication, and Background Tasks."""

from datetime import datetime
from typing import Any, Optional
from pydantic import BaseModel, ConfigDict, Field, field_validator


# ==========================================
# Book Schemas
# ==========================================

class BookBase(BaseModel):
    """Base schema containing common book attributes."""

    title: str = Field(..., min_length=1, description="Title of the book")
    author: str = Field(..., min_length=1, description="Author of the book")
    price: float = Field(..., gt=0, description="Price of the book (must be positive > 0)")
    genre: str = Field(..., min_length=1, description="Genre of the book")
    stock: int = Field(..., ge=0, description="Available stock quantity (must be non-negative >= 0)")

    @field_validator("title", "author", "genre")
    @classmethod
    def validate_non_empty_strings(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Field cannot be empty or contain only whitespace")
        return v.strip()


class BookCreate(BookBase):
    """Schema for creating a new book. ID is optional; auto-generated if omitted."""

    id: Optional[int] = Field(
        default=None,
        gt=0,
        description="Optional book ID. Auto-generated by the database if not provided.",
    )


class BookUpdate(BaseModel):
    """Schema for updating an existing book. All fields are optional."""

    id: Optional[int] = Field(
        default=None,
        gt=0,
        description="Book ID (ignored during update; URL path ID is used)",
    )
    title: Optional[str] = Field(default=None, min_length=1, description="Title of the book")
    author: Optional[str] = Field(default=None, min_length=1, description="Author of the book")
    price: Optional[float] = Field(default=None, gt=0, description="Price of the book (must be positive > 0)")
    genre: Optional[str] = Field(default=None, min_length=1, description="Genre of the book")
    stock: Optional[int] = Field(
        default=None, ge=0, description="Available stock quantity (must be non-negative >= 0)"
    )

    @field_validator("title", "author", "genre")
    @classmethod
    def validate_non_empty_strings_optional(cls, v: Optional[str]) -> Optional[str]:
        if v is not None:
            if not v.strip():
                raise ValueError("Field cannot be empty or contain only whitespace")
            return v.strip()
        return v


class Book(BookBase):
    """Full schema for a book, supporting ORM serialization."""

    id: int = Field(..., gt=0, description="Unique book identifier")
    user_id: Optional[int] = Field(default=None, description="ID of the user who created this book")

    model_config = ConfigDict(
        from_attributes=True,
        json_schema_extra={
            "example": {
                "id": 1,
                "title": "Clean Code",
                "author": "Robert C. Martin",
                "price": 29.99,
                "genre": "Software Engineering",
                "stock": 15,
                "user_id": 1,
            }
        },
    )


BookResponse = Book


# ==========================================
# User & Authentication Schemas
# ==========================================

class UserBase(BaseModel):
    """Base schema for user accounts."""

    username: str = Field(..., min_length=1, description="Unique username")
    role: str = Field(default="user", description="User role ('user' or 'admin')")

    @field_validator("username")
    @classmethod
    def validate_username(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Username cannot be empty or contain only whitespace")
        return v.strip()

    @field_validator("role")
    @classmethod
    def validate_role(cls, v: str) -> str:
        if not v or not v.strip():
            return "user"
        cleaned = v.strip().lower()
        if cleaned not in ("user", "admin"):
            raise ValueError("Role must be either 'user' or 'admin'")
        return cleaned


class UserRegister(BaseModel):
    """Schema for user registration."""

    username: str = Field(..., min_length=1, description="Unique username")
    password: str = Field(..., min_length=1, description="User password")
    role: Optional[str] = Field(default="user", description="Role: 'user' or 'admin'")

    @field_validator("username")
    @classmethod
    def validate_username(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Username cannot be empty or contain only whitespace")
        return v.strip()

    @field_validator("password")
    @classmethod
    def validate_password(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Password cannot be empty or contain only whitespace")
        return v

    @field_validator("role")
    @classmethod
    def validate_role(cls, v: Optional[str]) -> str:
        if v is None or not v.strip():
            return "user"
        cleaned = v.strip().lower()
        if cleaned not in ("user", "admin"):
            raise ValueError("Role must be either 'user' or 'admin'")
        return cleaned


class UserLogin(BaseModel):
    """Schema for JSON login request."""

    username: str = Field(..., min_length=1, description="Username")
    password: str = Field(..., min_length=1, description="Password")


class UserResponse(BaseModel):
    """Schema for public user responses (never exposes password or hash)."""

    id: int = Field(..., description="Unique user ID")
    username: str = Field(..., description="Username")
    role: str = Field(..., description="Role of the user ('user' or 'admin')")

    model_config = ConfigDict(
        from_attributes=True,
        json_schema_extra={
            "example": {
                "id": 1,
                "username": "john_doe",
                "role": "user",
            }
        },
    )


class Token(BaseModel):
    """JWT Bearer token response."""

    access_token: str
    token_type: str = "bearer"


class TokenData(BaseModel):
    """Decoded JWT payload data."""

    username: Optional[str] = None
    role: Optional[str] = None


# ==========================================
# Note Schemas (Relational Data Model)
# ==========================================

class NoteBase(BaseModel):
    """Base schema for relational Notes."""

    title: str = Field(..., min_length=1, description="Note title")
    content: str = Field(..., min_length=1, description="Note body content")

    @field_validator("title", "content")
    @classmethod
    def validate_non_empty(cls, v: str) -> str:
        if not v or not v.strip():
            raise ValueError("Field cannot be empty or contain only whitespace")
        return v.strip()


class NoteCreate(NoteBase):
    """Schema for creating a note."""
    pass


class NoteResponse(NoteBase):
    """DTO response for a note with user relation ID and creation timestamp."""

    id: int
    user_id: int
    created_at: datetime

    model_config = ConfigDict(from_attributes=True)


class NoteWithUserResponse(NoteResponse):
    """Relational join response showing Note and its associated User."""

    user: UserResponse


class UserDetailResponse(UserResponse):
    """Relational join response showing User with associated Books and Notes."""

    books: list[Book] = []
    notes: list[NoteResponse] = []

    model_config = ConfigDict(from_attributes=True)


# ==========================================
# Background Tasks & Notification Schemas (Task 4)
# ==========================================

class EmailNotificationRequest(BaseModel):
    """Request payload for dispatching an async background email."""

    recipient: str = Field(..., min_length=3, description="Recipient email address")
    subject: str = Field(..., min_length=1, description="Email subject line")
    message: str = Field(..., min_length=1, description="Email message body")


class WebhookDispatchRequest(BaseModel):
    """Request payload for dispatching an async background webhook."""

    url: str = Field(..., min_length=4, description="Target webhook URL")
    event: str = Field(..., min_length=1, description="Event name (e.g. 'book.purchased')")
    payload: dict[str, Any] = Field(default_factory=dict, description="Event payload data")


class NotificationTaskResponse(BaseModel):
    """Response returned immediately when a background task is queued."""

    message: str
    task_id: str
    task_type: str
    target: str
    status: str = "queued"


class BookOrderRequest(BaseModel):
    """Request payload for ordering a book."""

    quantity: int = Field(default=1, gt=0, description="Quantity to purchase (must be > 0)")
    buyer_email: Optional[str] = Field(
        default=None, description="Email address for order confirmation"
    )
    webhook_url: Optional[str] = Field(
        default=None, description="Optional webhook URL to receive order event"
    )


class BookOrderResponse(BaseModel):
    """Response returned upon successful book purchase."""

    message: str
    book_id: int
    quantity: int
    total_price: float
    remaining_stock: int
    background_task_id: Optional[str] = None
